#!/usr/bin/env node
/**
 * Emits supabase/seed.sql from the compiled library.
 *
 * The file is idempotent: every insert upserts on the primary key and sparks for a book are
 * replaced wholesale, so re-running it after a content rebuild updates the library in place
 * rather than erroring or duplicating. It is written as one transaction so a partial content
 * load can never leave the database half-updated.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const lib = JSON.parse(readFileSync('content/dist/library.json', 'utf8'));

/** Postgres literal quoting. Everything user-visible goes through here. */
const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (list) => `array[${(list ?? []).map(q).join(', ')}]::text[]`;
const json = (v) => (v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`);

const out = [];
out.push('-- Dogear content seed — generated by scripts/gen-seed-sql.mjs. Do not edit by hand.');
out.push(`-- ${lib.counts.books} books · ${lib.counts.sparks} sparks · generated ${lib.generated_at}`);
out.push('');
out.push('begin;');
out.push('');

out.push('-- Categories ----------------------------------------------------------------');
lib.categories.forEach((c, i) => {
  out.push(
    `insert into public.categories (id, label, short, blurb, accent, foreground, tint, tint_dark, sort_order) values (${[
      q(c.id), q(c.label), q(c.short), q(c.blurb), q(c.accent), q(c.foreground), q(c.tint), q(c.tintDark), i,
    ].join(', ')})`
  );
  out.push(
    '  on conflict (id) do update set label = excluded.label, short = excluded.short, blurb = excluded.blurb, ' +
      'accent = excluded.accent, foreground = excluded.foreground, tint = excluded.tint, ' +
      'tint_dark = excluded.tint_dark, sort_order = excluded.sort_order;'
  );
});
out.push('');

out.push('-- Books ---------------------------------------------------------------------');
for (const b of lib.books) {
  out.push(
    `insert into public.books (id, title, subtitle, author, year, category_id, subcategory, tags, difficulty, ` +
      `read_time_min, why_it_matters, crux_headline, crux_body, actions, if_you_liked, not_for_you_if, ` +
      `confidence, verification_notes) values (${[
        q(b.id), q(b.title), q(b.subtitle ?? null), q(b.author), b.year, q(b.category), q(b.subcategory ?? null),
        arr(b.tags), q(b.difficulty), b.read_time_min ?? 10, q(b.why_it_matters), q(b.crux.headline), q(b.crux.body),
        arr(b.actions), arr(b.if_you_liked), q(b.not_for_you_if), q(b.verification?.confidence ?? 'high'),
        q(b.verification?.notes ?? null),
      ].join(', ')})`
  );
  out.push(
    '  on conflict (id) do update set title = excluded.title, subtitle = excluded.subtitle, ' +
      'author = excluded.author, year = excluded.year, category_id = excluded.category_id, ' +
      'subcategory = excluded.subcategory, tags = excluded.tags, difficulty = excluded.difficulty, ' +
      'read_time_min = excluded.read_time_min, why_it_matters = excluded.why_it_matters, ' +
      'crux_headline = excluded.crux_headline, crux_body = excluded.crux_body, actions = excluded.actions, ' +
      'if_you_liked = excluded.if_you_liked, not_for_you_if = excluded.not_for_you_if, ' +
      'confidence = excluded.confidence, verification_notes = excluded.verification_notes;'
  );
}
out.push('');

out.push('-- Sparks --------------------------------------------------------------------');
out.push('-- Replaced per book so a rebuild that drops or reorders a spark stays consistent.');
for (const b of lib.books) {
  out.push(`delete from public.sparks where book_id = ${q(b.id)};`);
  const values = b.sparks.map((s, i) =>
    `  (${[
      q(s.id), q(b.id), i + 1, q(s.hook), q(s.insight), q(s.why), q(s.apply), q(s.format),
      json(s.format === 'carousel' ? s.carousel ?? null : null), arr(s.tags),
    ].join(', ')})`
  );
  out.push(
    'insert into public.sparks (id, book_id, position, hook, insight, why, apply, format, carousel, tags) values'
  );
  out.push(values.join(',\n') + ';');
}
out.push('');
out.push('commit;');
out.push('');

const sql = out.join('\n');
writeFileSync('supabase/seed.sql', sql);
console.log(
  `supabase/seed.sql · ${lib.counts.books} books · ${lib.counts.sparks} sparks · ${(sql.length / 1024 / 1024).toFixed(2)} MB`
);
